def seed_additional_surveys(db):
    for title, description, questions in SURVEYS:
        if db.query(Survey).filter_by(title=title).first():
            continue
        survey = Survey(title=title, description=description, is_active=True)
        survey.questions = [
            SurveyQuestion(question_text=text, question_type="single_choice", options_text=options)
            for text, options in questions
        ]
        db.add(survey)
    db.commit()
